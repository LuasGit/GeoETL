\set ON_ERROR_STOP on
BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_fecha (
    clave_fecha INTEGER PRIMARY KEY,
    fecha DATE NOT NULL UNIQUE,
    anio SMALLINT NOT NULL,
    trimestre SMALLINT NOT NULL,
    mes SMALLINT NOT NULL,
    dia SMALLINT NOT NULL,
    dia_semana SMALLINT NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_fuente (
    clave_fuente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_fuente VARCHAR(30) NOT NULL UNIQUE,
    nombre_fuente VARCHAR(100) NOT NULL,
    proveedor VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS dw.dim_fenomeno (
    clave_fenomeno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_fenomeno VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    descripcion TEXT
);
CREATE TABLE IF NOT EXISTS dw.hecho_observacion (
    clave_hecho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_fecha INTEGER NOT NULL REFERENCES dw.dim_fecha(clave_fecha),
    clave_fuente INTEGER NOT NULL REFERENCES dw.dim_fuente(clave_fuente),
    clave_fenomeno INTEGER NOT NULL REFERENCES dw.dim_fenomeno(clave_fenomeno),
    id_observacion_origen UUID NOT NULL UNIQUE REFERENCES core.observacion_ambiental(id_observacion),
    cantidad_observaciones SMALLINT NOT NULL DEFAULT 1 CHECK (cantidad_observaciones=1),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_hecho_fecha_fenomeno ON dw.hecho_observacion(clave_fecha,clave_fenomeno);
CREATE INDEX IF NOT EXISTS ix_hecho_fuente_fecha ON dw.hecho_observacion(clave_fuente,clave_fecha);

CREATE OR REPLACE VIEW dw.vw_observaciones_diarias AS
SELECT d.fecha, t.codigo_fenomeno AS fenomeno, t.nombre AS nombre_fenomeno,
       sum(h.cantidad_observaciones)::bigint AS cantidad
FROM dw.hecho_observacion h
JOIN dw.dim_fecha d ON d.clave_fecha=h.clave_fecha
JOIN dw.dim_fenomeno t ON t.clave_fenomeno=h.clave_fenomeno
GROUP BY d.fecha,t.codigo_fenomeno,t.nombre;

CREATE OR REPLACE VIEW dw.vw_observaciones_por_fuente AS
SELECT d.fecha, f.codigo_fuente AS fuente, sum(h.cantidad_observaciones)::bigint AS cantidad
FROM dw.hecho_observacion h
JOIN dw.dim_fecha d ON d.clave_fecha=h.clave_fecha
JOIN dw.dim_fuente f ON f.clave_fuente=h.clave_fuente
GROUP BY d.fecha,f.codigo_fuente;

CREATE OR REPLACE VIEW ops.vw_estado_fuentes AS
SELECT f.id_fuente, f.codigo, f.nombre, f.esta_activa, f.frecuencia_minutos,
       max(e.fecha_inicio) AS ultima_ejecucion,
       max(e.fecha_fin) FILTER (WHERE e.estado IN ('EXITO','PARCIAL')) AS ultima_extraccion_valida,
       count(e.id_ejecucion) AS ejecuciones,
       coalesce(sum(e.registros_recibidos),0)::bigint AS recibidos_acumulados,
       coalesce(sum(e.registros_rechazados),0)::bigint AS rechazados_acumulados
FROM ops.fuente_datos f
LEFT JOIN ops.ejecucion_ingesta e ON e.id_fuente=f.id_fuente
GROUP BY f.id_fuente;
COMMIT;
